CREATE TABLE IF NOT EXISTS workshop_lock (id INT PRIMARY KEY);
MERGE INTO workshop_lock KEY(id) VALUES (1);

CREATE TABLE IF NOT EXISTS profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS customer_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    customer VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS order_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES customer_order(id),
    profile_id BIGINT NOT NULL REFERENCES profile(id),
    length BIGINT NOT NULL CHECK (length > 0),
    quantity INT NOT NULL CHECK (quantity > 0),
    produced INT NOT NULL DEFAULT 0 CHECK (produced >= 0),
    held INT NOT NULL DEFAULT 0 CHECK (held >= 0),
    CHECK (produced + held <= quantity)
);

CREATE TABLE IF NOT EXISTS cut_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kerf BIGINT NOT NULL CHECK (kerf >= 0),
    trim BIGINT NOT NULL CHECK (trim >= 0),
    reusable BIGINT NOT NULL CHECK (reusable > 0),
    state VARCHAR(12) NOT NULL DEFAULT 'DRAFT' CHECK (state IN ('DRAFT','RESERVED','APPLIED','CANCELLED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_at TIMESTAMP WITH TIME ZONE,
    actual_hash VARCHAR(64)
);

CREATE TABLE IF NOT EXISTS plan_order (
    plan_id BIGINT NOT NULL REFERENCES cut_plan(id),
    order_id BIGINT NOT NULL REFERENCES customer_order(id),
    PRIMARY KEY(plan_id, order_id)
);

CREATE TABLE IF NOT EXISTS stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL REFERENCES profile(id),
    length BIGINT NOT NULL CHECK (length > 0),
    kind VARCHAR(8) NOT NULL CHECK (kind IN ('FULL','OFFCUT')),
    state VARCHAR(12) NOT NULL DEFAULT 'AVAILABLE' CHECK (state IN ('AVAILABLE','RESERVED','CONSUMED')),
    origin_id BIGINT REFERENCES stock(id),
    reserved_plan BIGINT REFERENCES cut_plan(id),
    version BIGINT NOT NULL DEFAULT 1,
    CHECK ((state = 'RESERVED' AND reserved_plan IS NOT NULL) OR (state <> 'RESERVED' AND reserved_plan IS NULL))
);

CREATE TABLE IF NOT EXISTS plan_bar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL REFERENCES cut_plan(id),
    stock_id BIGINT NOT NULL REFERENCES stock(id),
    stock_version BIGINT NOT NULL,
    expected BIGINT NOT NULL CHECK(expected >= 0),
    actual BIGINT CHECK(actual >= 0),
    offcut_id BIGINT REFERENCES stock(id),
    UNIQUE(plan_id, stock_id)
);

CREATE TABLE IF NOT EXISTS plan_cut (
    bar_id BIGINT NOT NULL REFERENCES plan_bar(id),
    line_id BIGINT NOT NULL REFERENCES order_line(id),
    quantity INT NOT NULL CHECK(quantity > 0),
    actual INT CHECK(actual >= 0 AND actual <= quantity),
    PRIMARY KEY(bar_id, line_id)
);

CREATE TABLE IF NOT EXISTS shortage (
    plan_id BIGINT NOT NULL REFERENCES cut_plan(id),
    line_id BIGINT NOT NULL REFERENCES order_line(id),
    quantity INT NOT NULL CHECK(quantity > 0),
    PRIMARY KEY(plan_id,line_id)
);

CREATE TABLE IF NOT EXISTS journal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(20) NOT NULL,
    detail VARCHAR(500) NOT NULL,
    happened_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS stock_availability ON stock(state, profile_id, length);
CREATE INDEX IF NOT EXISTS order_line_order ON order_line(order_id, id);
CREATE INDEX IF NOT EXISTS plan_bar_plan ON plan_bar(plan_id, id);
